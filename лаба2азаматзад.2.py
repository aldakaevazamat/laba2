import math


def check_point_in_figure_2(x, y, r):
    """
    Функция проверяет, попадает ли точка (x, y)
    в заштрихованную область на РИСУНКЕ 2.
    """

    # --- ЧАСТЬ 1: Левая верхняя четверть круга ---
    # Условия: x <= 0, y >= 0, и расстояние от центра <= R
    in_circle_part = (x <= 0) and (y >= 0) and (x ** 2 + y ** 2 <= r ** 2)

    # --- ЧАСТЬ 2: Правый нижний треугольник ---
    # Треугольник ограничен:
    # - осью X (y=0)
    # - линией y = -2x (левая сторона)
    # - линией y = 2(x - R) (правая сторона)

    in_triangle_part = False
    if (x >= 0) and (y <= 0):
        # Проверяем, что точка выше левой наклонной линии и выше правой наклонной линии
        # Также проверяем, что x не выходит за пределы R
        if (x <= r) and (y >= -2 * x) and (y >= 2 * (x - r)):
            in_triangle_part = True

    # Точка попадает в область, если она в круге ИЛИ в треугольнике
    return in_circle_part or in_triangle_part


def main():
    print("=== Задание 2: Проверка попадания точки в область ===")

    try:
        # Ввод данных
        x = float(input("Введите координату X: "))
        y = float(input("Введите координату Y: "))
        r = float(input("Введите параметр R (положительное число): "))

        if r <= 0:
            print("Ошибка: R должно быть больше нуля.")
            return

        # Вызов функции проверки
        result = check_point_in_figure_2(x, y, r)

        # Вывод результата
        if result:
            print(f"\nРЕЗУЛЬТАТ: Точка ({x}, {y}) ПОПАДАЕТ в заштрихованную область.")
        else:
            print(f"\nРЕЗУЛЬТАТ: Точка ({x}, {y}) НЕ ПОПАДАЕТ в заштрихованную область.")

    except ValueError:
        print("Ошибка: Введите корректные числовые значения.")


if __name__ == "__main__":
    main()